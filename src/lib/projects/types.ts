/**
 * Shared project types.
 *
 * No `fs`/`path` in here, so client components can import from this module
 * directly. The index re-exports everything for server code, but importing
 * types from there in a client component is one careless edit away from
 * dragging Node built-ins into the browser bundle.
 */

export interface Project {
  slug: string;
  title: string;
  description: string;
  category: string;
  techStack: string[];
  image?: string;
  github?: string;
  demo?: string;
  featured: boolean;
  context?: string;
  role?: string;
  goal?: string;
  features?: string[];
  pcb?: PcbAssets;
  source?: "curated" | "github";
  stars?: number;
  forks?: number;
  createdAt?: string;
  updatedAt?: string;
  license?: string;
  languages?: LanguageStat[];
  release?: Release;
  commits?: Commit[];
  contributors?: Contributor[];
  dependencies?: Dependency[];
  docs?: MarkdownDoc[];
  pdfs?: PdfDoc[];
  /** Image paths/URLs shown as a photo gallery (real board photos, screenshots). */
  gallery?: string[];
  /** A demo video: a YouTube/Vimeo URL or a path/URL to an .mp4 / .webm file. */
  video?: string;
  /** Measurement datasets (CSV) rendered as line charts. */
  measurements?: Measurement[];
}

/** A CSV dataset shown as a measurement line chart (first column X, rest Y series). */
export interface Measurement {
  /** Path/URL to the .csv. */
  src: string;
  /** Chart heading. */
  title?: string;
  /** Axis labels. */
  xLabel?: string;
  yLabel?: string;
}

/** Optional KiCad / 3D assets for the interactive PCB viewer. Paths are under /public. */
export interface PcbAssets {
  /** Path to the root .kicad_sch file, rendered as an interactive schematic. */
  schematic?: string;
  /**
   * All schematic source files (root + hierarchical sub-sheets, and the .kicad_pro
   * if present). KiCanvas only resolves sheets it's given, so every sheet is fed to
   * it and a sheet selector appears when there's more than one page.
   */
  schematicSheets?: string[];
  /** Path to a .kicad_pcb file, rendered as an interactive board layout. */
  board?: string;
  /** Path to a .glb / .gltf model, rendered as a rotatable 3D view. */
  model3d?: string;
  /** Path to a BOM .csv, rendered as an interactive (searchable/sortable) table. */
  bom?: string;
  // --- Diode-style pre-rendered images (SVG/PNG). When set, they replace the live
  // KiCanvas view for that tab. Generated by scripts/render-kicad-images.mjs. ---
  /** Static schematic image. */
  schematicImage?: string;
  /** Static PCB top view. */
  pcbImage?: string;
  /** Static PCB bottom view. */
  pcbBackImage?: string;
  /** Static PCB "X-ray" (all copper layers overlaid). */
  pcbXrayImage?: string;
}

export interface MarkdownDoc {
  /** Original file path in the repo, e.g. "docs/architecture.md". */
  path: string;
  /** Short button label, e.g. "architecture". */
  label: string;
  /** Rendered HTML. */
  html: string;
}

/** A PDF shown as an extra tab in the Documentation section. Paths are under /public. */
export interface PdfDoc {
  /** Public, URL-encoded path, e.g. "/docs/my-repo/project/power%20budget.pdf". */
  src: string;
  /** Original file path, e.g. "project/power budget.pdf". Used as tooltip + key. */
  path: string;
  /** Short tab label, e.g. "power budget". */
  label: string;
  /** Byte size when known; shown next to the download link. */
  size?: number;
}

export interface LanguageStat {
  name: string;
  percentage: number;
  color: string;
}

export interface Release {
  tag: string;
  name?: string;
  url: string;
  publishedAt?: string;
}

export interface Commit {
  sha: string;
  message: string;
  date?: string;
  url: string;
  authorLogin?: string;
  authorAvatar?: string;
}

export interface Contributor {
  login: string;
  avatarUrl: string;
  htmlUrl: string;
  contributions: number;
}

export interface Dependency {
  name: string;
  ecosystem: string;
}

export interface ProjectWithHtml extends Project {
  contentHtml: string;
}
